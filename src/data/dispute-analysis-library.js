/**
 * 根据纠纷类型和焦点键查找焦点解析
 * @param {string} disputeType - 纠纷类型键
 * @param {string} focusKey - 焦点键
 * @returns {object|null} 焦点解析对象
 */
export function getDisputeAnalysis(disputeType, focusKey) {
  const key = `${disputeType}:${focusKey}`;
  return disputeAnalysisLibrary[key] || null;
}

/**
 * 获取某纠纷类型的全部焦点解析
 * @param {string} disputeType - 纠纷类型键
 * @returns {object[]} 焦点解析对象数组
 */
export function getAllAnalysesForDispute(disputeType) {
  return Object.values(disputeAnalysisLibrary).filter(
    item => item.disputeType === disputeType
  );
}

/**
 * 根据焦点键数组批量获取焦点解析
 * @param {string} disputeType - 纠纷类型键
 * @param {string[]} focusKeys - 焦点键数组
 * @returns {object[]} 焦点解析对象数组
 */
export function getDisputeAnalyses(disputeType, focusKeys) {
  return focusKeys
    .map(key => getDisputeAnalysis(disputeType, key))
    .filter(Boolean);
}
